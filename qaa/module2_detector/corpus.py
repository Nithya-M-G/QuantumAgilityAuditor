"""
Module 2 - Labeled corpus construction for the NLP cryptographic classifier.

WHY THIS FILE EXISTS
--------------------
There is no public, ML-ready, labeled dataset of "code snippet -> cryptographic
algorithm" for post-quantum migration. The closest public artifacts are
CryptoAPI-Bench / ApacheCryptoAPI-Bench (181 + 121 Java cases, labeled for
*misuse* rather than *algorithm family*) and the rule bases of CBOM scanners.
Neither is large enough or labeled the way this classifier needs.

So the corpus is constructed programmatically from a grammar:

    template x library x language x identifier-style x obfuscation

Each template is a real API call shape taken from the actual documentation of
the library it imitates, so the lexical distribution is realistic even though
the corpus is synthetic. The obfuscation layer is the point of the whole
exercise: it produces aliased imports, wrapper functions, indirection through
config dictionaries, and misleading identifier names, which is exactly the class
of usage a keyword scanner misses and an NLP classifier should catch.

HONEST EVALUATION
-----------------
Two splits are produced by scripts/train_all.py:

  * random split    - snippets shuffled, stratified. This is the number most
                      papers report. It is optimistic, because near-identical
                      template instances land on both sides of the split.
  * template split  - entire template families are held out, so the test set
                      contains API shapes the model has never seen. This is the
                      honest generalisation number and it is the one to quote
                      when someone asks how it behaves on real code.

Both are written to models/nlp_metrics.json and both are shown in the dashboard.
"""

