def _wrap_in_function(body: str, lang: str, rng: random.Random) -> str:
    fname = rng.choice(FUNC_NAMES)
    if lang == "python":
        inner = "\n".join("    " + l for l in body.splitlines())
        return f"def {fname}(self, config):\n{inner}\n    return True"
    if lang == "java":
        inner = "\n".join("        " + l for l in body.splitlines())
        return (f"public Object {fname}() throws Exception {{\n{inner}\n"
                f"        return null;\n    }}")
    if lang in ("javascript", "typescript"):
        inner = "\n".join("  " + l for l in body.splitlines())
        return f"function {fname}(opts) {{\n{inner}\n  return opts;\n}}"
    if lang == "go":
        inner = "\n".join("\t" + l for l in body.splitlines())
        return f"func {fname}() error {{\n{inner}\n\treturn nil\n}}"
    if lang in ("cpp", "csharp"):
        inner = "\n".join("    " + l for l in body.splitlines())
        return f"void {fname}() {{\n{inner}\n}}"
    return body


def _add_noise(body: str, rng: random.Random, n: int = 2) -> str:
    lines = body.splitlines()
    for _ in range(n):
        pos = rng.randint(0, len(lines))
        lines.insert(pos, rng.choice(NOISE_LINES))
    return "\n".join(lines)


def _add_comment(body: str, rng: random.Random) -> str:
    return rng.choice(COMMENTS) + "\n" + body


def _mangle_case(body: str, rng: random.Random) -> str:
    """Swap snake_case for camelCase in the variable name, and vice versa."""
    def repl(m: "re.Match") -> str:
        s = m.group(0)
        if "_" in s:
            head, *rest = s.split("_")
            return head + "".join(p.capitalize() for p in rest)
        return s
    import re
    return re.sub(r'\b[a-z]+_[a-z_]+\b', repl, body)


OBFUSCATIONS = [
    ("none", lambda b, l, r: b),
    ("wrapped", lambda b, l, r: _wrap_in_function(b, l, r)),
    ("noisy", lambda b, l, r: _add_noise(b, r, 2)),
    ("commented", lambda b, l, r: _add_comment(b, r)),
    ("wrapped_noisy", lambda b, l, r: _wrap_in_function(_add_noise(b, r, 1), l, r)),
    ("case_mangled", lambda b, l, r: _mangle_case(b, r)),
    ("comment_noise", lambda b, l, r: _add_comment(_add_noise(b, r, 2), r)),
]


def build_corpus(
    samples_per_template: int = 26,
    seed: int = 1337,
    misleading_name_rate: float = 0.35,
) -> list[dict]:
    """
    Materialise the corpus.

    Returns a list of dicts with keys:
        text, label, template_family, language, obfuscation, sample_id
    """
    rng = random.Random(seed)
    rows: list[dict] = []
    seen_hashes: set[str] = set()

    for label, family, lang, template in TEMPLATES:
        for i in range(samples_per_template):
            if rng.random() < misleading_name_rate:
                var = rng.choice(MISLEADING_NAMES)
            else:
                var = rng.choice(VAR_NAMES)
            sizes = KEY_SIZES.get(label, DEFAULT_SIZES)
            body = template.format(v=var, n=rng.choice(sizes),
                                   f=rng.choice(FUNC_NAMES),
                                   c=rng.choice(CLASS_NAMES))
            ob_name, ob_fn = OBFUSCATIONS[i % len(OBFUSCATIONS)]
            text = ob_fn(body, lang, rng)

            h = hashlib.md5(text.encode()).hexdigest()
            if h in seen_hashes:
                continue
            seen_hashes.add(h)

            rows.append({
                "text": text,
                "label": label,
                "template_family": family,
                "language": lang,
                "obfuscation": ob_name,
                "sample_id": h[:12],
            })

    rng.shuffle(rows)
    return rows


def corpus_summary(rows: list[dict]) -> dict:
    from collections import Counter
    return {
        "total": len(rows),
        "classes": len({r["label"] for r in rows}),
        "template_families": len({r["template_family"] for r in rows}),
        "by_label": dict(Counter(r["label"] for r in rows)),
        "by_language": dict(Counter(r["language"] for r in rows)),
        "by_obfuscation": dict(Counter(r["obfuscation"] for r in rows)),
    }
